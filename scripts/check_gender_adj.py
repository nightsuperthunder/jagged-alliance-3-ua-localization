"""Додаткова перевірка роду «я + прикметник/неправильне дієслово» (впевнений/рада, зміг/змогла) проти статі мовця
(narrator = Емма, жінка) і російської версії. python scripts/check_gender_adj.py work/gender_adj.json"""
import json,re,sys
from collections import Counter
sys.path.insert(0,'scripts')
s=json.load(open('work/strings.json',encoding='utf-8'));t=json.load(open('work/translations.json',encoding='utf-8'))
ru=json.load(open('work/ref_Russian.json',encoding='utf-8'))
W=r"[А-Яа-яІіЇїЄєҐґ’']"
ADJ_M=r"(впевнений|певен|радий|вдячний|змушений|готовий|винний|згоден|згодний|зобов’язаний|переконаний|здивований|вражений|щасливий|втомлений|задоволений|голодний|зайнятий|самий|сам|один|живий|потрібен|потрібний|сповнений|стривожений|засмучений|розчарований|приголомшений|наляканий|певний|упевнений|народжений|поранений|п’яний|злий|дурний|старий|молодий|єдиний|останній|перший|був|міг|зміг|допоміг|втік|ніс|приніс|ліг|пішов|прийшов|знайшов|зайшов|вийшов|дійшов|мусив)"
ADJ_F=r"(впевнена|певна|рада|вдячна|змушена|готова|винна|згодна|зобов’язана|переконана|здивована|вражена|щаслива|втомлена|задоволена|голодна|зайнята|сама|одна|жива|потрібна|сповнена|стривожена|засмучена|розчарована|приголомшена|налякана|народжена|поранена|п’яна|зла|дурна|стара|молода|єдина|остання|перша|була|могла|змогла|допомогла|втекла|несла|принесла|лягла|пішла|прийшла|знайшла|зайшла|вийшла|дійшла|мусила)"
RM=re.compile(rf"(?<!{W})я(?!{W})(?:\s+(?:не|теж|також|ж|вже|ще|дуже|так|справді|зовсім|просто|точно|аж|був|була|)){{0,2}}\s+{ADJ_M}(?!{W})",re.I)
RF=re.compile(rf"(?<!{W})я(?!{W})(?:\s+(?:не|теж|також|ж|вже|ще|дуже|так|справді|зовсім|просто|точно|аж|був|була|)){{0,2}}\s+{ADJ_F}(?!{W})",re.I)
RUF=re.compile(r"(?<![а-яё])(уверена|рада|должна|готова|благодарна|сама|одна|была|могла|смогла|пришла|нашла|ушла|вынуждена|виновата|согласна|счастлива|удивлена|поражена|довольна|занята|жива)(?![а-яё])",re.I)
RUM=re.compile(r"(?<![а-яё])(уверен|рад|должен|готов|благодарен|сам|один|был|мог|смог|пришел|пришёл|нашел|нашёл|ушел|ушёл|вынужден|виноват|согласен|счастлив|удивлен|поражен|доволен|занят|жив)(?![а-яё])",re.I)
rows=[];c=Counter()
for x in s:
  r=t.get(x['key']);
  if not r or r.get('status') not in('ok','manual') or not r.get('uk'): continue
  uk=r['uk']; g=x.get('gender','') or ('f' if (x.get('speaker') or '')=='narrator' else '')
  m=bool(RM.search(uk)); f=bool(RF.search(uk))
  if m==f: continue
  ug='m' if m else 'f'
  rr=ru.get(x['key'],''); rg={'f'} if RUF.search(rr) and not RUM.search(rr) else {'m'} if RUM.search(rr) and not RUF.search(rr) else set()
  why=None
  if g and g!=ug: why='speaker'
  elif not g and len(rg)==1 and ug not in rg: why='ru'
  if why: c[why]+=1; rows.append((x['key'],why,x.get('speaker'),g,uk,rr))
print(c)
json.dump(rows,open(sys.argv[1],'w',encoding='utf-8'),ensure_ascii=False,indent=0)
for k,w,sp,g,uk,rr in rows[:25]: print(k,w,sp,g,'|',uk[:90].replace('\n',' '),'|RU:',rr[:60].replace('\n',' '))
